'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
// Current registration/location contract is an explicit user change; earlier snapshots are preserved in .local.
// These hashes detect later drift. Semantic tests below must still enforce the actual new contract.
const expected = require('../docs/api/contracts.sha256.json');
for (const [file, sha] of Object.entries(expected)) {
  const raw = fs.readFileSync(path.resolve(__dirname, '..', file));
  const normalized = Buffer.from(raw.toString('utf8').replace(/\r\n/g, '\n'));
  const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
  assert.ok(hash(raw) === sha || hash(normalized) === sha,
    'Contract differs from the current snapshot: ' + file + '. Review the diff; do not blindly rebaseline.');
}
const {routes} = require('../gateway/identity-routes.cjs');
assert.equal(routes.length, 48);
assert.deepEqual(routes.find(route => route.operation === 'listNearbyDrivers').roles, ['CUSTOMER','ADMIN']);
assert.equal(routes.filter(route => route.service === 'auth').length, 5);
assert.equal(routes.filter(route => route.service === 'customer').length, 4);
const YAML=require('yaml');
const auth=YAML.parse(fs.readFileSync(path.join(__dirname,'../docs/api/01-auth.yaml'),'utf8')).components.schemas;
assert.deepEqual(auth.LoginInput.required,['email','password']);
assert.equal(auth.LoginInput.properties.phone,undefined);
assert.equal(auth.RegisterInput.properties.role,undefined);
assert.equal(auth.RegisterInput.properties.name,undefined);
assert.equal(auth.RegisterInput.properties.password.minLength,1);
assert.equal(auth.LoginInput.properties.password.minLength,1);
assert.equal(auth.RegisterInput.properties.password.maxLength,undefined);
for (const name of ['RegisterInput','RequestOtpInput','VerifyOtpInput','Account']) {
  assert.equal(auth[name].properties.phone.type,'string');
  assert.equal(auth[name].properties.phone.minLength,1);
  assert.equal(auth[name].properties.phone.pattern,undefined);
  assert.equal(auth[name].properties.phone.maxLength,undefined);
}
assert.equal(auth.RegisterInput.properties.cid,undefined);
assert.equal(auth.RegisterInput.properties.did,undefined);
assert.deepEqual(auth.RegisterInput.required,['email','password','phone']);
assert.ok(auth.RegisterInput.properties.plateNumber&&auth.RegisterInput.properties.code);
assert.ok(routes.find(r=>r.operation==='registerAccount').responses.has(202));
assert.equal(auth.Registration.properties.profileStatus, undefined);
assert.equal(auth.Registration.properties.accessToken, undefined);
assert.deepEqual(Object.keys(auth.Session.properties).sort(), ['accessToken','account']);
